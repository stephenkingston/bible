/// Glyph width of a Tamil grapheme in cells, or `None` for anything the
/// table doesn't cover (other scripts, rare signs).
pub(super) fn width(g: &str) -> Option<f32> {
    let mut chars = g.chars();
    let first = chars.next()?;
    let row = BASES.iter().position(|&b| b == first)?;
    let rest: String = chars.collect();
    // Two-part vowel signs can arrive decomposed.
    let sign = match rest.as_str() {
        "" => None,
        "\u{0BC6}\u{0BBE}" => Some('\u{0BCA}'),
        "\u{0BC7}\u{0BBE}" => Some('\u{0BCB}'),
        "\u{0BC6}\u{0BD7}" => Some('\u{0BCC}'),
        s if s.chars().count() == 1 => s.chars().next(),
        _ => return None,
    };
    let col = match sign {
        None => 0,
        Some(s) => 1 + SIGNS.iter().position(|&x| x == s)?,
    };
    match TENTHS[row][col] {
        0 => None,
        n => Some(f32::from(n) / 10.0),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn syllables_have_glyph_widths() {
        let ka = width("க").unwrap();
        let kaa = width("கா").unwrap();
        let ko = width("கொ").unwrap();
        assert!(ka > 1.0 && ka < kaa && kaa < ko, "{ka} {kaa} {ko}");
        // The pulli adds no width; ண is one of the widest letters.
        assert_eq!(width("க்"), Some(ka));
        assert!(width("ண").unwrap() > ka);
        // Same syllable with the two-part vowel sign decomposed.
        assert_eq!(width("\u{0B95}\u{0BC6}\u{0BBE}"), Some(ko));
        assert_eq!(width("a"), None);
        assert_eq!(width("அா"), None);
    }
}
